/** Nombre corto de cada nivel (el metal); «Única» para las de un solo nivel. */
export const LEVEL_LABEL: Readonly<Record<Level, string>> = { 0: 'Única', 1: 'Bronce', 2: 'Plata', 3: 'Oro', 4: 'Platino', 5: 'Diamante' };

/** Metal con que se pinta cada nivel (§4.3): la única se pinta en oro, sin puntos. */
export const LEVEL_TIER: Readonly<Record<Level, 'bronce' | 'plata' | 'oro' | 'platino' | 'diamante'>> = {
  0: 'oro',
  1: 'bronce',
  2: 'plata',
  3: 'oro',
  4: 'platino',
  5: 'diamante',
};

export const levelDef = (def: BadgeDef, level: Level): LevelDef | undefined => def.levels.find((l) => l.level === level);

/** Umbral de un nivel para esas variantes (el puesto en los podios). */
export const thresholdOf = (def: BadgeDef, level: Level, sport?: VariantArg): number | undefined =>
  pickVariant(levelDef(def, level)?.threshold, variantList(sport));

/** Rareza estimada de un nivel en un deporte. */
export const rarityOf = (def: BadgeDef, level: Level, sport?: VariantArg): RarityTarget | undefined =>
  pickVariant(levelDef(def, level)?.rarity, variantList(sport));

/** ¿El valor llega al nivel? (`gte`: llega al umbral; `lt`: queda por debajo; sin umbral: no se mide así). */
function reaches(def: BadgeDef, l: LevelDef, value: number, variants: readonly Variant[]): boolean {
  const t = pickVariant(l.threshold, variants);
  if (t === undefined) return false;
  if (def.compare === 'gte') return value >= t;
  if (def.compare === 'lt') return value < t;
  if (def.compare === 'place') return value === t;
  return false;
}

/** Todos los niveles que alcanza un valor (cada nivel es una fila propia), de menor a mayor. */
export function levelsReached(def: BadgeDef, value: number, sport?: VariantArg): Level[] {
  const variants = variantList(sport);
  return def.levels.filter((l) => reaches(def, l, value, variants)).map((l) => l.level);
}

/** El nivel más alto que alcanza un valor; null si ninguno. */
export function levelFor(def: BadgeDef, value: number, sport?: VariantArg): Level | null {
  const got = levelsReached(def, value, sport);
  return got.length ? got[got.length - 1] : null;
}

/** El siguiente nivel que falta y su umbral (para `badge_progress`); null si ya tiene el más alto o no se mide. */
export function nextLevel(def: BadgeDef, value: number, sport?: VariantArg): { level: Level; target: number } | null {
  if (def.compare !== 'gte' && def.compare !== 'lt') return null;
  const variants = variantList(sport);
  for (const l of def.levels) {
    if (reaches(def, l, value, variants)) continue;
    const target = pickVariant(l.threshold, variants);
    return target === undefined ? null : { level: l.level, target };
  }
  return null;
}

/** Nivel de un puesto en un podio: 1.º oro (3), 2.º plata (2), 3.º bronce (1). */
export function placeLevel(place: number): Level | null {
  return place === 1 ? 3 : place === 2 ? 2 : place === 3 ? 1 : null;
}

/** ¿Esta insignia (o esta cara) pide aval? */
export const needsAval = (def: BadgeDef, alt?: string | null): boolean => !!def.aval || (!!alt && !!def.alts?.[alt]?.aval);

