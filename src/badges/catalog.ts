/** Rellena `{clave}` con los valores; lo que no viene se queda como está. */
export function fillText(template: string, vars: Readonly<Partial<Record<Placeholder, string | number>>>): string {
  return template.replace(/\{([a-z_]+)\}/g, (all, k: string) => {
    const v = vars[k as Placeholder];
    return v === undefined ? all : String(v);
  });
}

/** Las llaves que usa un texto. */
export const placeholdersIn = (template: string): string[] => [...template.matchAll(/\{([a-z_]+)\}/g)].map((m) => m[1]);

export interface TextOptions {
  sport?: BadgeSport;
  /** Variantes ya resueltas (3x3, 9 hoyos); si no, las del deporte. */
  variants?: readonly Variant[];
  level?: Level;
  /** Cara de la insignia (`context.alt`). */
  alt?: string | null;
}

const optVariants = (o: TextOptions) => o.variants ?? variantsOf(o.sport ?? 'all');
const altOf = (def: BadgeDef, alt: string | null | undefined): BadgeAlt | undefined => (alt ? def.alts?.[alt] : undefined);

/** Nombre de la insignia (plantilla: `year_recap` lleva `{anio}`). */
export function nameOf(def: BadgeDef, o: TextOptions = {}): string {
  return altOf(def, o.alt)?.name ?? pickVariant(def.name, optVariants(o)) ?? def.key;
}

/** Nombre del nivel: el propio ('Pavo', 'Primer lugar') o el metal. */
export function levelNameOf(def: BadgeDef, level: Level, o: Omit<TextOptions, 'level'> = {}): string {
  return pickVariant(def.levelNames?.[level], optVariants(o)) ?? LEVEL_LABEL[level];
}

/** Descripción (plantilla) de lo que se ganó. */
export function descriptionOf(def: BadgeDef, o: TextOptions = {}): string {
  const v = optVariants(o);
  return (
    altOf(def, o.alt)?.description ??
    (o.level !== undefined ? pickVariant(def.levelDescriptions?.[o.level], v) : undefined) ??
    pickVariant(def.description, v) ??
    ''
  );
}

/** Cómo se gana (plantilla), para las bloqueadas. */
export const howOf = (def: BadgeDef, o: Omit<TextOptions, 'level' | 'alt'> = {}): string => pickVariant(def.how, optVariants(o)) ?? '';

/** Unidad del progreso en singular o plural según `n` («Te faltan 3 juegos»). */
export function unitOf(def: BadgeDef, n: number, o: Omit<TextOptions, 'level' | 'alt'> = {}): string {
  const u = pickVariant(def.unit, optVariants(o));
  return u ? (n === 1 ? u[0] : u[1]) : '';
}

