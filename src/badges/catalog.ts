/** Niveles 1, 2, 3… con su umbral y la rareza de cada uno ('C PC R E'). */
function tiers(rarities: string, thresholds: readonly ByVariant<number>[], extra: readonly (Partial<LevelDef> | undefined)[] = []): LevelDef[] {
  const r = rarities.split(' ') as Rarity[];
  if (r.length !== thresholds.length) throw new Error('catálogo: rarezas y umbrales no cuadran');
  return thresholds.map((threshold, i) => ({ level: (i + 1) as Level, threshold, rarity: r[i], ...extra[i] }));
}

/** Un solo nivel (el 0, «única»). */
const one = (rarity: ByVariant<RarityTarget>, threshold?: ByVariant<number>): LevelDef[] => [
  threshold === undefined ? { level: 0, rarity } : { level: 0, rarity, threshold },
];

/** Podio: oro = 1.º (nivel 3), plata = 2.º (nivel 2), bronce = 3.º (nivel 1). El umbral es el puesto. */
const podium = (gold: Rarity, silver: Rarity, bronze: Rarity): LevelDef[] => [
  { level: 1, threshold: 3, rarity: bronze },
  { level: 2, threshold: 2, rarity: silver },
  { level: 3, threshold: 1, rarity: gold },
];

const units = (singular: string, plural: string) => [singular, plural] as const;

