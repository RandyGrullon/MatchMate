export const badgesForSport = (sport: BadgeSport): BadgeDef[] =>
  BADGES.filter((d) => (sport === 'all' ? d.sports === 'all' : d.sports !== 'all' && d.sports.includes(sport)));

/** Las insignias que se apagan o no con `badges_auto` en una liga (las de cuenta no dependen de eso). */
export function allowedBy(def: BadgeDef, mode: BadgesAuto): boolean {
  if (def.scope === 'cuenta') return true;
  if (mode === 'ninguna') return false;
  return mode === 'todas' || !def.title;
}

