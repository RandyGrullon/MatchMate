// Valores por deporte o variante

/**
 * Variantes de una fila, de la más específica a la más general: baloncesto 3x3 → `['basketball3x3',
 * 'basketball']`; golf de 9 hoyos → `['golf9', 'golf']`; 'all' → `[]` (solo `default`).
 */
export function variantsOf(sport: BadgeSport, opts: { is3x3?: boolean; nineHoles?: boolean } = {}): Variant[] {
  if (sport === 'all') return [];
  if (sport === 'basketball' && opts.is3x3) return ['basketball3x3', 'basketball'];
  if (sport === 'golf' && opts.nineHoles) return ['golf9', 'golf'];
  return [sport];
}

const isByVariantObject = <T>(v: ByVariant<T>): v is Readonly<Partial<Record<Variant | 'default', T>>> =>
  typeof v === 'object' && v !== null && !Array.isArray(v);

/** El valor para esas variantes: el primero que exista, si no `default`; undefined si no hay. */
export function pickVariant<T>(value: ByVariant<T> | undefined, variants: readonly Variant[]): T | undefined {
  if (value === undefined) return undefined;
  if (!isByVariantObject(value)) return value as T;
  for (const v of variants) if (value[v] !== undefined) return value[v];
  return value.default;
}

/** Deporte de la fila, una variante ('basketball3x3', 'golf9') o la lista ya armada con `variantsOf`. */
export type VariantArg = BadgeSport | Variant | readonly Variant[];

function variantList(arg: VariantArg | undefined): readonly Variant[] {
  if (arg === undefined || arg === 'all') return [];
  if (typeof arg !== 'string') return arg;
  if (arg === 'basketball3x3') return ['basketball3x3', 'basketball'];
  if (arg === 'golf9') return ['golf9', 'golf'];
  return [arg];
}

/** Un parámetro del criterio (`params`) para un deporte o variante. */
export const paramOf = (def: BadgeDef, name: string, sport?: VariantArg): number | undefined => pickVariant(def.params?.[name], variantList(sport));

